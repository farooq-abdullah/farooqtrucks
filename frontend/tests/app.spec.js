import { mkdir, readFile, writeFile } from 'node:fs/promises';
const captureDir = '../artifacts';
async function capture(page, name) {
  if (name === 'desktop-plan' || name.endsWith('-route')) await expect(page.locator('.map-wrap:visible')).toBeVisible();
  await page.evaluate(() => document.fonts.ready);
  if (await page.locator('.map-wrap:visible').count()) {
    await expect(page.locator('.leaflet-container:visible')).toBeVisible();
    await expect(page.locator('.route-waypoint').first()).toBeVisible();
    await expect(page.locator('.map-wrap:visible')).toHaveAttribute('data-tiles-ready', 'true', { timeout: 25000 });
    await expect.poll(() => page.locator('.leaflet-tile-loaded').evaluateAll(tiles => tiles.length > 0 && tiles.every(tile => Number(getComputedStyle(tile).opacity) >= 0.99)), { timeout: 25000 }).toBeTruthy();
  }
  await page.waitForTimeout(200);
  await mkdir(captureDir, { recursive: true }); await page.screenshot({ path: `${captureDir}/${name}.png`, fullPage: true });
}
async function assertFits(page) { expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy(); }

