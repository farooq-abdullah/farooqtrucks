test('field validation, provider error, help dialog and cancellation', async ({ page }) => {
  let planningRequests = 0;
  page.on('request', request => { if (request.method() === 'POST' && request.url().includes('/api/trips/plan/')) planningRequests += 1; });
  await page.goto('/');
  await page.getByRole('combobox', { name: 'Current location', exact: true }).fill('');
  await page.getByRole('button', { name: 'Plan route & logs →' }).click();
  await expect(page.getByText('Enter a city and state, or a full address.')).toBeVisible();
  await page.getByRole('combobox', { name: 'Current location', exact: true }).fill('Chicago, IL');
  const cycle = page.getByRole('spinbutton', { name: 'Current cycle used (hrs)', exact: true });
  await cycle.fill('71');
  await expect(page.getByText('Enter hours between 0 and 70.')).toBeVisible();
  await expect(cycle).toHaveAttribute('aria-invalid', 'true');
  expect(planningRequests).toBe(0);
  await page.getByRole('combobox', { name: 'Pickup location', exact: true }).fill('Springfield, IL');
  await expect(page.getByText('Enter hours between 0 and 70.')).toBeVisible();
  await page.getByRole('button', { name: 'Plan route & logs →' }).click(); await expect(page.getByText('Enter hours between 0 and 70.')).toBeVisible();
  expect(planningRequests).toBe(0);
  for (const invalid of ['-1', '']) {
    await cycle.fill(invalid);
    await expect(page.getByText('Enter hours between 0 and 70.')).toBeVisible();
  }
  for (const valid of ['0', '70', '20.5']) {
    await cycle.fill(valid);
    await expect(page.getByText('Enter hours between 0 and 70.')).toBeHidden();
    await expect(cycle).toHaveAttribute('aria-invalid', 'false');
  }
  await cycle.fill('20');
  await page.route('**/api/trips/plan/', route => route.fulfill({ status: 502, contentType: 'application/json', body: JSON.stringify({ detail: 'The map service is unavailable. Please try again shortly.' }) }));
  await page.getByRole('button', { name: 'Plan route & logs →' }).click(); await expect(page.getByRole('alert')).toContainText('The map service is unavailable');
  await page.getByRole('button', { name: 'Explain cycle hours' }).click(); await expect(page.getByRole('dialog')).toContainText('34-hour rest'); await page.getByRole('button', { name: 'Got it' }).click();
  await page.unroute('**/api/trips/plan/');
  await page.route('**/api/trips/plan/', route => new Promise(resolve => setTimeout(() => { route.abort().catch(() => {}); resolve(); }, 1000)));
  await page.getByRole('button', { name: 'Plan route & logs →' }).click(); await expect(page.getByRole('button', { name: 'Cancel', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Cancel', exact: true }).click(); await expect(page.getByRole('button', { name: 'Plan route & logs →' })).toBeEnabled();
});

test('70 used hours: real restart, multiple log days, optional details and print all sheets', async ({ page }) => {
  await page.goto('/'); await page.getByRole('spinbutton', { name: 'Current cycle used (hrs)', exact: true }).fill('70');
  const responsePromise = page.waitForResponse(r => r.url().includes('/api/trips/plan/') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Plan route & logs →' }).click(); const response = await responsePromise;
  expect(response.status()).toBe(200); const plan = await response.json();
  expect(plan.summary.cycle_restarts).toBe(1); expect(plan.daily_logs.length).toBeGreaterThan(1);
  expect(plan.events[0].duration_seconds).toBe(34 * 3600);
  await page.getByRole('button', { name: 'Review log sheets →' }).click();
  await expect(page.locator('.day-choice')).toHaveCount(plan.daily_logs.length);
  await page.locator('.day-choice').last().click(); await expect(page.locator('.log-desktop .log-sheet')).toHaveAttribute('aria-label', `Daily log ${plan.daily_logs.at(-1).date}`);
  await page.getByRole('button', { name: 'Sheet details', exact: true }).click();
  await page.getByRole('textbox', { name: 'Driver', exact: true }).fill('Farooq'); await page.getByRole('textbox', { name: 'Carrier name', exact: true }).fill('farooqtrucks');
  await page.getByRole('button', { name: 'Save details' }).click(); await expect(page.locator('.log-desktop .sheet-details')).toContainText('Farooq');
  await expect(page.getByRole('textbox', { name: /signature/i })).toHaveCount(0);
  await page.locator('.day-choice').first().click();
  await page.locator('.log-desktop [data-log-activity^="Cycle restart"] .activity-hit').hover();
  await expect(page.getByRole('tooltip')).toContainText('Full activity:');
  await expect(page.getByRole('tooltip')).toContainText('earlier daily hours');
  await page.locator('.log-desktop [data-log-activity^="Cycle restart"]').press('Escape');
  await page.locator('.day-choice').last().click();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByText(/driver.s signature/i)).toHaveCount(0);
  await page.getByRole('tab', { name: 'Route', exact: true }).click();
  const savedDownload = page.waitForEvent('download'); await page.getByRole('button', { name: 'Download plan', exact: true }).click();
  const saved = await savedDownload; const savedPlan = JSON.parse(await readFile(await saved.path(), 'utf-8'));
  expect(savedPlan).not.toHaveProperty('sheet_signatures');
  expect(savedPlan.sheet_details).toEqual({ driver: 'Farooq', carrier: 'farooqtrucks' });
  await page.getByRole('tab', { name: 'Daily logs', exact: true }).click();
  await page.evaluate(() => { window.print = () => { window.__printCalled = true; window.dispatchEvent(new Event('afterprint')); }; });
  await page.getByRole('button', { name: 'Print logs', exact: true }).click(); await expect.poll(() => page.evaluate(() => window.__printCalled)).toBeTruthy();
  await expect(page.locator('.print-only .log-sheet')).toHaveCount(plan.daily_logs.length);
  await expect(page.locator('.print-only')).not.toContainText(/signature|unsigned/i);
  await expect(page.locator('.print-only .log-sheet').last().locator('.sheet-details')).toContainText('Farooq');
  await page.emulateMedia({ media: 'print' }); await capture(page, 'print-multiple-days');
  await expect(page.locator('.skip-link')).toBeHidden();
  const pdf = await page.pdf({ path: `${captureDir}/planned-logs.pdf`, preferCSSPageSize: true, printBackground: true });
  expect((pdf.toString('latin1').match(/\/Type\s*\/Page\b/g) || []).length).toBe(plan.daily_logs.length);
});
